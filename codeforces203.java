import java.util.*;
public class codeforces203
{
    public static void main(String args[])                 // Problem 2185A. Perfect Root
    {
        Scanner sc=new Scanner(System.in);
        int t=sc.nextInt();
        while(t-->0)
            {
                int n=sc.nextInt();
                for(int i=1;i<=n;i++)
                {
                    System.out.println(i+" ");
                }
            }        
    }

}
